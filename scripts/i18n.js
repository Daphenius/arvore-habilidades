let LANG = null;
// O idioma do usuário só é conhecido no "i18nInit". Antes disso, game.i18n.lang é o idioma
// padrão do servidor (Configuração do Foundry), que pode ser outro: se ele fosse guardado
// cedo, a Árvore ficava em português com o Foundry do jogador em inglês.
let READY = false;
export function i18nReady() { READY = true; LANG = null; CACHE.clear(); }
globalThis.Hooks?.once?.("i18nInit", i18nReady);
// "pt" ou "en". Enquanto o Foundry não informa o idioma, fica em português.
export function isEnglish() {
  if (LANG) return LANG === "en";
  if (!READY) return false;
  const l = globalThis.game?.i18n?.lang;
  if (!l) return false;
  LANG = String(l).toLowerCase().startsWith("pt") ? "pt" : "en";
  return LANG === "en";
}
export const setLang = l => { LANG = l ? (String(l).toLowerCase().startsWith("pt") ? "pt" : "en") : null; READY = true; CACHE.clear(); };

// começo de trecho que ainda é o fim de uma tag: `">`, `" class="on">`, `>`
function leadTag(part) {
  const i = part.indexOf(">");
  if (i < 0) return "";
  const pre = part.slice(0, i + 1);
  if (pre.includes("<")) return "";
  if (pre.trim() === ">" || pre.trim() === "/>" || /^\s*"/.test(pre) || /="/.test(pre) || /^\s*[a-zA-Z-]+(\s[^>]*)?>$/.test(pre) && !/\s\S+\s\S+\s/.test(pre)) return pre;
  return "";
}
export function splitChunk(chunk) {
  const out = [];
  for (const part of chunk.split(/(<\/?[a-zA-Z!][^>]*>?)/)) {
    if (!part) continue;
    if (/^<\/?[a-zA-Z!]/.test(part)) { out.push({ t: "tag", s: part }); continue; }
    const lead = leadTag(part);
    if (lead) out.push({ t: "tag", s: lead });
    const rest = part.slice(lead.length);
    if (!rest) continue;
    // trecho de atributos sem "<" (ex.: 'class="x" data-tooltip="Texto"')
    if (/(^|\s|")[a-zA-Z-]+="/.test(rest)) out.push({ t: "tag", s: rest }); else out.push({ t: "text", s: rest });
  }
  return out;
}
export const ATTR_RE = /\b(placeholder|data-tooltip|title|aria-label)="([^"]*)/g;

const CACHE = new Map();
function trText(s) {
  const t = s.trim();
  const e = t && EN[t];
  return e ? s.replace(t, () => e) : s;
}
function trChunk(s) {
  if (!s || !/[A-Za-zÀ-ú]/.test(s)) return s;
  let out = CACHE.get(s);
  if (out !== undefined) return out;
  const whole = EN[s.trim()];
  out = whole ? trText(s) : splitChunk(s).map(p => p.t === "text" ? trText(p.s) : p.s.replace(ATTR_RE, (m, a, v) => `${a}="${trText(v)}`)).join("");
  CACHE.set(s, out);
  return out;
}
// L`texto ${valor}` ou L("texto")
export function L(strings, ...vals) {
  if (typeof strings === "string") return isEnglish() ? trChunk(strings) : strings;
  const en = isEnglish();
  let out = "";
  for (let i = 0; i < strings.length; i++) {
    out += en ? trChunk(strings[i]) : strings[i];
    if (i < vals.length) out += vals[i];
  }
  return out;
}
// listas montadas na importação (rótulos de opções): traduz depois que o idioma é conhecido
export function relabel(values) {
  if (!isEnglish()) return;
  for (const v of values) {
    // objetos de rótulos { chave: "texto" }
    if (v && typeof v === "object" && !Array.isArray(v) && Object.getPrototypeOf(v) === Object.prototype) {
      for (const [k, x] of Object.entries(v)) if (typeof x === "string" && EN[x.trim()]) v[k] = trChunk(x);
      continue;
    }
    if (!Array.isArray(v)) continue;
    for (const o of v) if (o && typeof o === "object") for (const k of ["label", "name", "hint"]) if (typeof o[k] === "string") o[k] = trChunk(o[k]);
  }
}

